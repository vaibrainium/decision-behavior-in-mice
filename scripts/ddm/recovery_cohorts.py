"""Cohort-level model recovery for the control-only paper (plan .agents/plans/2026-10-29-control-paper.md step 3b, D002
item 2, D004): does the Fig 3 group test (common model C beats each alternative over 10 mice) also come out when the
data are generated by that alternative?

  - per dataset and alternative X: d = (test_nll_X - test_nll_C) / n_test * 1000 (> 0: C predicts better);
  - cohorts: all 2^10 = 1,024 choices of one replicate per mouse; per cohort a one-sample t over mice per X, Holm over
    the alternatives; the cohort reproduces the result for X if mean d_X > 0 and Holm p_X < 0.05;
  - X is separated if <= 10% of X-generated and >= 50% of C-generated cohorts reproduce it (decisive: E and ES);
  - while ES fits are missing, E is also judged with Bonferroni x4 (conservative) and Holm over the 3 available.
Secondary: per-dataset counts (> 10 NLL) with Clopper-Pearson CIs, and the best-fitting candidate per dataset.

Usage: python -m scripts.ddm.recovery_cohorts [--recovery_dir ddm/recovery_full_cpu_resp] [--suffix _v2]
"""

import argparse
import itertools
import pickle
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

from config import dir_config
from scripts.ddm import model_recovery as mr

TABLES = Path(__file__).resolve().parents[2] / "dissemination/paper_control/tables"
DATE = "2026-10-30"
NAMES = {mr.COMMON: "C", mr.EXTREMA: "E", mr.EXTREMA_SAMPLES: "ES", "DDMx": "DDMx", "ESx": "ESx"}
ALTERNATIVES = ["E", "ES", "DDMx", "ESx"]
DECISIVE = ["E", "ES"]


def holm(p: np.ndarray) -> np.ndarray:
    order, adj, run = np.argsort(p), np.empty(len(p)), 0.0
    for i, k in enumerate(order):
        run = max(run, (len(p) - i) * p[k])
        adj[k] = min(run, 1.0)
    return adj


def load(recovery_dir: Path) -> pd.DataFrame:
    rows = []
    for f in sorted(recovery_dir.glob("*.pkl")):
        with open(f, "rb") as fh:
            r = pickle.load(fh)
        rows.append({"mouse": r["mouse"], "generator": NAMES[r["generator"]], "candidate": NAMES[r["candidate"]], "replicate": r["replicate"],
                     "n_test": r["n_test"], "test_nll": r["test_nll"]})
    return pd.DataFrame(rows)


def differences(df: pd.DataFrame) -> pd.DataFrame:
    """d per (generator, mouse, replicate) and alternative, wide: one column per available alternative."""
    wide = df.pivot_table(index=["generator", "mouse", "replicate"], columns="candidate", values="test_nll")
    n = df.groupby(["generator", "mouse", "replicate"]).n_test.first()
    alts = [x for x in ALTERNATIVES if x in wide.columns]
    d = wide[alts].sub(wide["C"], axis=0).div(n, axis=0) * 1000
    return d


def cohorts(d: pd.DataFrame, generator: str) -> pd.DataFrame:
    g = d.loc[generator].dropna(axis=1, how="any")
    mice = sorted(g.index.get_level_values("mouse").unique())
    alts = list(g.columns)
    out = []
    for choice in itertools.product([0, 1], repeat=len(mice)):
        x = np.stack([g.loc[(m, r)].to_numpy() for m, r in zip(mice, choice)])
        t = stats.ttest_1samp(x, 0.0, axis=0)
        row = {"generator": generator, "replicates": "".join(map(str, choice))}
        h = holm(t.pvalue)
        for j, a in enumerate(alts):
            row |= {f"mean_{a}": x[:, j].mean(), f"p_{a}": t.pvalue[j], f"holm_{a}": h[j],
                    f"rep_{a}": bool(x[:, j].mean() > 0 and h[j] < 0.05),
                    f"rep_bonf4_{a}": bool(x[:, j].mean() > 0 and min(4 * t.pvalue[j], 1.0) < 0.05)}
        out.append(row)
    return pd.DataFrame(out)


def clopper_pearson(k: int, n: int) -> tuple[float, float]:
    ci = stats.binomtest(k, n).proportion_ci(method="exact")
    return ci.low, ci.high


def main(recovery_dir: Path, suffix: str = "") -> None:
    df = load(recovery_dir)
    d = differences(df)
    generators = set(d.index.get_level_values("generator"))
    complete = all(a in d.columns for a in ALTERNATIVES) and not d.isna().any().any() and {"C", *ALTERNATIVES} <= generators
    TABLES.mkdir(parents=True, exist_ok=True)

    coh = pd.concat([cohorts(d, g) for g in sorted(d.index.get_level_values("generator").unique())])
    coh.to_csv(TABLES / f"recovery_cohorts_{DATE}{suffix}.csv", index=False)
    rates = coh.groupby("generator")[[c for c in coh.columns if c.startswith("rep_")]].mean()
    rates.to_csv(TABLES / f"recovery_cohort_rates_{DATE}{suffix}.csv")
    print("Share of 1,024 cohorts that reproduce the Fig 3 result (rows: generator):")
    print(rates.round(3).to_string())

    print("\nSeparation (X-generated <= 0.10 and C-generated >= 0.50):")
    for x in DECISIVE:
        if x not in d.columns:
            print(f"  {x}: candidate fits missing")
            continue
        for col in [f"rep_{x}", f"rep_bonf4_{x}"]:
            if x not in rates.index:
                print(f"  {x} ({col}): {x}-generated data missing")
                continue
            px, pc = rates.loc[x, col], rates.loc["C", col]
            print(f"  {x} ({col}): P(rep | {x}) = {px:.3f}, P(rep | C) = {pc:.3f} -> separated: {px <= 0.10 and pc >= 0.50}")
    print(f"\nAll 4 alternatives fitted and generated: {complete} ({'final' if complete else 'PROVISIONAL'})")

    per = []
    for (g, a), s in d.stack().rename("d").reset_index().rename(columns={"level_3": "candidate"}).groupby(["generator", "candidate"]):
        n_obs = s.merge(df[["generator", "mouse", "replicate", "n_test"]].drop_duplicates(), on=["generator", "mouse", "replicate"])
        summed = n_obs.d * n_obs.n_test / 1000
        k_c, k_a, n = int((summed > 10).sum()), int((summed < -10).sum()), len(summed)
        per.append({"generator": g, "alternative": a, "n_datasets": n, "mean_d": s.d.mean(), "c_better_10": k_c,
                    "c_better_10_ci": clopper_pearson(k_c, n), "alt_better_10": k_a, "alt_better_10_ci": clopper_pearson(k_a, n)})
    per = pd.DataFrame(per)
    per.to_csv(TABLES / f"recovery_per_dataset_{DATE}{suffix}.csv", index=False)
    print("\nPer dataset (> 10 NLL):")
    print(per.round(3).to_string())

    best = df.loc[df.groupby(["generator", "mouse", "replicate"]).test_nll.idxmin()]
    conf = pd.crosstab(best.generator, best.candidate)
    conf.to_csv(TABLES / f"recovery_confusion_{DATE}{suffix}.csv")
    print("\nBest held-out candidate per dataset (rows: generator):")
    print(conf.to_string())


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--recovery_dir", default="ddm/recovery_full_cpu_resp")
    parser.add_argument("--suffix", default="", help="appended to table names so earlier versions are not overwritten")
    args = parser.parse_args()
    main(Path(dir_config.data.processed) / args.recovery_dir, args.suffix)
